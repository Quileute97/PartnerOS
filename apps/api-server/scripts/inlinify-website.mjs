import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = join(fileURLToPath(import.meta.url), '..');
// scripts/ is inside apps/api-server/, so two up = monorepo root
const root = join(__dirname, '..', '..');
const websiteDist = join(root, 'website', 'dist');
const outFile = join(__dirname, '..', 'src', 'spa-static.ts');

// Recursively collect all files under websiteDist (relative to dist root)
const entries = [];
function walk(dir, rel) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const relPath = rel ? posix.join(rel, name) : name;
    if (statSync(full).isDirectory()) {
      walk(full, relPath);
    } else {
      entries.push(relPath);
    }
  }
}
walk(websiteDist, '');

const SPA = {};
for (const rel of entries.sort()) {
  SPA[`/${rel}`] = readFileSync(join(websiteDist, rel), 'utf8');
}

const src = `// AUTO-GENERATED by scripts/inlinify-website.mjs — do not edit by hand.
// Bundles the built PartnerOS website (apps/website/dist) so the Cloudflare Worker
// can serve the SPA + static assets at runtime.
export const SPA_ASSETS = ${JSON.stringify(SPA, null, 2)};
`;

writeFileSync(outFile, src, 'utf8');
console.log(`Generated ${outFile}`);
console.log(`  entries: ${Object.keys(SPA).length}`);
console.log(`  bytes:   ${src.length}`);
